/**
 * 合併後的完整速查表：核心手冊 6 條 ＋ 擴充手冊 10 條 ＋ 公測修訂 1 條。
 *
 * 核心 6 條使用各自的專屬欄位與 UI；擴充 10 條使用通用的 `sections` 陣列
 * （見 `ruleCodexExpansion.js` 檔頭說明）。三者形狀不同但共用同一個抽屜。
 */
export const RULE_CODEX = {
  ...CORE_CODEX,
  ...EXPANSION_CODEX,
  ...PLAYTEST_CODEX
};

export function findCodexRule(term) {
  if (!term) return null;
  const lower = term.toLowerCase().trim();
  for (const key of Object.keys(RULE_CODEX)) {
    const item = RULE_CODEX[key];
    if (item.id === lower || item.title === term || item.keywords.some(k => k === term || lower === k.toLowerCase())) {
      return item;
    }
  }
  return null;
}
